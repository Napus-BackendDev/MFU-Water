export function getTimelineDayByIndex(index) {
  const safeIdx = Math.max(0, Math.min(FLOOD_TIMELINE_DATA.length - 1, Math.round(index)));
  return FLOOD_TIMELINE_DATA[safeIdx];
}

import { THATON_RIVER_SEGMENT, generateSmoothFloodBuffer } from './thatonFloodData';

export function getTimelineFloodPolygonGeoJSON(index) {
  const safeIdx = Math.max(0, Math.min(FLOOD_TIMELINE_DATA.length - 1, index));
  const floorIdx = Math.floor(safeIdx);
  const ceilIdx = Math.min(FLOOD_TIMELINE_DATA.length - 1, Math.ceil(safeIdx));
  const t = safeIdx - floorIdx;

  const b1 = FLOOD_TIMELINE_DATA[floorIdx].bufferMeters;
  const b2 = FLOOD_TIMELINE_DATA[ceilIdx].bufferMeters;
  const currentBuffer = b1 + (b2 - b1) * t;

  const currentDay = getTimelineDayByIndex(safeIdx);
  const polygonCoords = generateSmoothFloodBuffer(THATON_RIVER_SEGMENT, currentBuffer);

  return {
    type: 'FeatureCollection',
    features: [
      {
        type: 'Feature',
        properties: {
          dayIndex: currentDay.dayIndex,
          date: currentDay.date,
          displayDate: currentDay.displayDate,
          label: currentDay.phaseLabel,
          waterLevel: currentDay.waterLevelDiff,
          affectedAreaRai: currentDay.affectedAreaRai,
          bufferMeters: currentBuffer
        },
        geometry: {
          type: 'Polygon',
          coordinates: [polygonCoords]
        }
      }
    ]
  };
}
