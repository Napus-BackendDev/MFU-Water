for (const rel of ['docs/canvas-backup-2026-10-26.excalidraw', 'docs/product-scope.excalidraw']) {
  const full = path.join(ROOT, rel);
  if (!fs.existsSync(full)) continue;
  const doc = JSON.parse(fs.readFileSync(full, 'utf8'));
  doc.elements = doc.elements.filter(e => !String(e.id).startsWith('nw_s'));
  doc.elements.push(...newBlocks);
  doc.files = doc.files || {};
  Object.assign(doc.files, fileMap);
  fs.writeFileSync(full, Buffer.from(JSON.stringify(doc, null, 2), 'utf8'));
  console.log('Updated:', rel, 'elements:', doc.elements.length, 'files:', Object.keys(doc.files).length);
}
