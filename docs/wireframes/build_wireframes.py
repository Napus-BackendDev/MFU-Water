def mapbox(x,y,w,h,caption='แผนที่เชิงโครงสร้าง — ไม่อ้างพิกัดจริง',multi=False):
    rect(x,y,w,h,'#e5e9e8')
    for k in range(1,5):
        line(x+30,y+k*h/5,x+w-30,y+k*h/5,'#d1d9d6')
        line(x+k*w/5,y+30,x+k*w/5,y+h-30,'#d1d9d6')
    parts.append(f'<path d="M{x+80} {y+80} L{x+w*.55} {y+60} L{x+w-70} {y+h*.6} L{x+w*.4} {y+h-50}Z" fill="#d1d9d7" stroke="#a7b4af" stroke-dasharray="8 7"/>')
